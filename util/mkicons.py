root = sys.argv[1] if len(sys.argv) > 1 else "forth"
rows = [[line for line in art.strip().splitlines()] for art in ICONS.values()]
assert all(len(icon) == 16 and all(len(line) == 16 for line in icon) for icon in rows), "an icon is 16 by 16"
with open(f"{root}/icons.fs", "w") as f:
    f.write("\\ icons.fs - the pictures of HexaPaint's tools: " + ", ".join(ICONS) + "\n"
            "\\ GENERATED by util/mkicons.py, where they are drawn.  Do not edit.\n\\\n"
            "\\ One bitmap of them side by side, 128 pixels by 16, as the display is.\n\n"
            "bulk\ncreate icon-bits\n")
    for y in range(16):
        bits = "".join("1" if c == "#" else "0" for icon in rows for c in icon[y])
        f.write(" ".join(f"${int(bits[i:i + 64], 2):x} px," for i in range(0, len(bits), 64)) + "\n")
    f.write("unbulk\n")
print(f"{len(ICONS)} icons written to {root}/icons.fs")
