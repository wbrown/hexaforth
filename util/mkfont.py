#!/usr/bin/env python3
"""Generate forth/font.fs and forth/keymap.fs.

font.fs    Two fonts for ASCII 32-126, each 16 rows high:
             mono   GNU Unifont, which is drawn on an 8x16 grid, so the
                    bitmaps are exact and every character is 8 wide
             sans   DejaVu Sans Bold at 11 pixels, each character as wide
                    as it is
           A font is a strike: every glyph side by side in one bitmap, and
           a table of where each starts.  In the file it is five cells
           (height, first character, how many, cells in a row of the
           strike, and a zero the system uses), then where each glyph starts and where the last ends,
           then the strike, 64 pixels to a line with the leftmost highest.
           cross.fs lays those down in the display's own order (px,).
keymap.fs  Linux key codes (as virtio-input reports them) to ASCII: 128
           entries unshifted, then 128 shifted.  Cursor keys get codes
           from 128 up.
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

UNIFONT = "/usr/share/fonts/opentype/unifont/unifont.otf"
SANS = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
FIRST, COUNT, HEIGHT = 32, 95, 16


def cells(data):
    data += bytes(-len(data) % 8)
    return [f"${struct.unpack_from('<Q', data, i)[0]:x} ," for i in range(0, len(data), 8)]


def glyphs(path, size, top, fixed=None):
    """Each character as (width, rows), a row being a list of 0 and 1."""
    face = ImageFont.truetype(path, size)
    out = []
    for code in range(FIRST, FIRST + COUNT):
        width = fixed or max(1, round(face.getlength(chr(code))))
        im = Image.new("1", (width, HEIGHT), 0)
        draw = ImageDraw.Draw(im)
        draw.fontmode = "1"
        draw.text((0, top), chr(code), font=face, fill=1)
        out.append((width, [[1 if im.getpixel((x, y)) else 0 for x in range(width)]
                            for y in range(HEIGHT)]))
    return out


def strike(name, chars):
    starts = [0]
    for width, _ in chars:
        starts.append(starts[-1] + width)
    stride = (starts[-1] + 63) // 64
    lines = [f"header {name} create {name}",
             f"#{HEIGHT} , #{FIRST} , #{COUNT} , #{stride} , #0 ,"]
    lines += [" ".join(f"#{s} ," for s in starts[i:i + 12]) for i in range(0, len(starts), 12)]
    for y in range(HEIGHT):
        row = [bit for _, rows in chars for bit in rows[y]]
        row += [0] * (64 * stride - len(row))
        lines.append(" ".join(
            f"${int(''.join(map(str, row[i:i + 64])), 2):x} px," for i in range(0, len(row), 64)))
    return lines


def keymap():
    plain, shifted = bytearray(128), bytearray(128)

    def row(first, lower, upper):
        for i, (a, b) in enumerate(zip(lower, upper)):
            plain[first + i], shifted[first + i] = ord(a), ord(b)

    row(2, "1234567890-=", "!@#$%^&*()_+")
    row(16, "qwertyuiop[]", "QWERTYUIOP{}")
    row(30, "asdfghjkl;'`", 'ASDFGHJKL:"~')
    row(43, "\\zxcvbnm,./", "|ZXCVBNM<>?")
    row(71, "789-456+1230.", "789-456+1230.")        # keypad
    for code, value in ((1, 27), (14, 8), (15, 9), (28, 13), (57, 32), (55, 42), (96, 13),
                        (98, 47), (103, 128), (108, 129), (105, 130), (106, 131),
                        (104, 132), (109, 133), (102, 134), (107, 135), (111, 127)):
        plain[code] = shifted[code] = value
    return bytes(plain + shifted)


root = sys.argv[1] if len(sys.argv) > 1 else "forth"
with open(f"{root}/font.fs", "w") as f:
    f.write("\\ font.fs - the fonts: mono from GNU Unifont, sans from DejaVu Sans Bold\n"
            "\\ GENERATED by util/mkfont.py.  Do not edit.\n\n")
    f.write("\n".join(strike("mono", glyphs(UNIFONT, 16, 0, fixed=8))) + "\n\n")
    f.write("\n".join(strike("sans", glyphs(SANS, 11, 1))) + "\n")
with open(f"{root}/keymap.fs", "w") as f:
    f.write("\\ keymap.fs - key codes to ASCII, unshifted then shifted\n"
            "\\ GENERATED by util/mkfont.py.  Do not edit.\n\nheader keymap create keymap\n")
    f.write("\n".join(cells(keymap())) + "\n")
