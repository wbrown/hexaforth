#!/usr/bin/env python3
"""Generate forth/font.fs and forth/keymap.fs.

font.fs    8x16 glyphs for ASCII 32-126, rendered from GNU Unifont, which is
           drawn on an 8x16 grid, so the bitmaps are exact.  16 bytes per
           glyph, top row first, most significant bit leftmost.
keymap.fs  Linux key codes (as virtio-input reports them) to ASCII: 128
           entries unshifted, then 128 shifted.  Cursor keys get codes
           from 128 up.
"""
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

UNIFONT = "/usr/share/fonts/opentype/unifont/unifont.otf"


def cells(data):
    data += bytes(-len(data) % 8)
    return [f"${struct.unpack_from('<Q', data, i)[0]:x} ," for i in range(0, len(data), 8)]


def font():
    face = ImageFont.truetype(UNIFONT, 16)
    out = b""
    for code in range(32, 127):
        im = Image.new("1", (8, 16), 0)
        ImageDraw.Draw(im).text((0, 0), chr(code), font=face, fill=1)
        for y in range(16):
            out += bytes([sum(im.getpixel((x, y)) << (7 - x) for x in range(8))])
    return out


def keymap():
    plain, shifted = bytearray(128), bytearray(128)

    def row(first, lower, upper):
        for i, (a, b) in enumerate(zip(lower, upper)):
            plain[first + i], shifted[first + i] = ord(a), ord(b)

    row(2, "1234567890-=", "!@#$%^&*()_+")
    row(16, "qwertyuiop[]", "QWERTYUIOP{}")
    row(30, "asdfghjkl;'`", 'ASDFGHJKL:"~')
    row(43, "\\zxcvbnm,./", "|ZXCVBNM<>?")
    row(71, "789-456+1230.", "789-456+1230.")        # keypad
    for code, value in ((1, 27), (14, 8), (15, 9), (28, 13), (57, 32), (55, 42), (96, 13),
                        (98, 47), (103, 128), (108, 129), (105, 130), (106, 131),
                        (104, 132), (109, 133), (102, 134), (107, 135), (111, 127)):
        plain[code] = shifted[code] = value
    return bytes(plain + shifted)


def write(path, title, name, data):
    with open(path, "w") as f:
        f.write(f"\\ {title}\n\\ GENERATED by util/mkfont.py.  Do not edit.\n\nheader {name} create {name}\n")
        f.write("\n".join(cells(data)) + "\n")


root = sys.argv[1] if len(sys.argv) > 1 else "forth"
write(f"{root}/font.fs", "font.fs - 8x16 glyphs for ASCII 32-126, from GNU Unifont", "font", font())
write(f"{root}/keymap.fs", "keymap.fs - key codes to ASCII, unshifted then shifted", "keymap", keymap())
